"""Render a Code 39 barcode as a YUV4MPEG2 file for Chromium's fake camera.

The file is regenerated by `bun run bench:camera`, not committed: raw y4m is
large and trivially reproducible. Chromium loops it, so a few frames suffice.

Chromium's --use-file-for-fake-video-capture reads raw y4m, so no encoder is
needed. The barcode is the ANSI MH10.8.2 door-label form: the VIN preceded by
the `I` data identifier, wrapped in Code 39 start/stop characters.
"""
import sys

# Code 39: 9 elements per character, alternating bar/space starting with a bar.
# 1 = wide, 0 = narrow. Exactly three elements are wide in every character.
CODE39 = {
    "0": "000110100", "1": "100100001", "2": "001100001", "3": "101100000",
    "4": "000110001", "5": "100110000", "6": "001110000", "7": "000100101",
    "8": "100100100", "9": "001100100", "A": "100001001", "B": "001001001",
    "C": "101001000", "D": "000011001", "E": "100011000", "F": "001011000",
    "G": "000001101", "H": "100001100", "I": "001001100", "J": "000011100",
    "K": "100000011", "L": "001000011", "M": "101000010", "N": "000010011",
    "O": "100010010", "P": "001010010", "Q": "000000111", "R": "100000110",
    "S": "001000110", "T": "000010110", "U": "110000001", "V": "011000001",
    "W": "111000000", "X": "010010001", "Y": "110010000", "Z": "011010000",
    "-": "010000101", ".": "110000100", " ": "011000100", "$": "010101000",
    "/": "010100010", "+": "010001010", "%": "000101010", "*": "010010100",
}

def bars(text, narrow=3, ratio=3):
    """Yield (is_bar, width) for the whole symbol including start/stop."""
    for ch in "*" + text + "*":
        pattern = CODE39[ch]
        for i, wide in enumerate(pattern):
            yield (i % 2 == 0, narrow * (ratio if wide == "1" else 1))
        yield (False, narrow)  # inter-character gap

def render(text, width=1280, height=720, bar_height=260, narrow=3):
    elements = list(bars(text, narrow=narrow))
    symbol = sum(w for _, w in elements)
    if symbol > width - 2 * 10 * narrow:
        raise SystemExit(f"symbol {symbol}px does not fit in {width}px")
    x0 = (width - symbol) // 2
    y0 = (height - bar_height) // 2
    luma = bytearray(b"\xff" * (width * height))  # white background
    x = x0
    for is_bar, w in elements:
        if is_bar:
            for y in range(y0, y0 + bar_height):
                row = y * width
                luma[row + x : row + x + w] = b"\x00" * w
        x += w
    return luma

def write_y4m(path, luma, width, height, frames=8, fps=30):
    chroma = b"\x80" * ((width // 2) * (height // 2))
    with open(path, "wb") as f:
        f.write(f"YUV4MPEG2 W{width} H{height} F{fps}:1 Ip A1:1 C420\n".encode())
        for _ in range(frames):
            f.write(b"FRAME\n")
            f.write(bytes(luma))
            f.write(chroma)
            f.write(chroma)

if __name__ == "__main__":
    payload = sys.argv[1] if len(sys.argv) > 1 else "I1HGCM82633A004352"
    out = sys.argv[2] if len(sys.argv) > 2 else "bench/fake-camera.y4m"
    W, H = 1280, 720
    write_y4m(out, render(payload, W, H), W, H)
    print(f"wrote {out}: Code 39 of {payload!r} at {W}x{H}")
